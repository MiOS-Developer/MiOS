# Sentence & Clause Boundary Splitter
# ==============================================================================

class SentenceChunker:
    """Splits streamed text tokens into complete sentence and clause chunks.

    Enables concurrent synthesis of earlier sentences while subsequent text
    is still being streamed or generated by an LLM.
    """

    def __init__(self, max_clause_chars: int = 120):
        self.max_clause_chars = max_clause_chars
        self.buffer = ""

    def _is_abbreviation(self, text: str, dot_pos: int) -> bool:
        """Check if dot is part of a known abbreviation or decimal."""
        # Decimal check: e.g. 3.14
        if dot_pos > 0 and dot_pos + 1 < len(text):
            if text[dot_pos - 1].isdigit() and text[dot_pos + 1].isdigit():
                return True

        # Preceding word check
        start = dot_pos - 1
        while start >= 0 and (text[start].isalnum() or text[start] == "_"):
            start -= 1
        word = text[start + 1:dot_pos].lower()
        return word in ABBREVIATIONS

    def feed(self, chunk: str) -> List[str]:
        """Feed text token/chunk and return list of completed sentence chunks."""
        if not chunk:
            return []

        self.buffer += chunk
        emitted: List[str] = []

        while True:
            # Look for sentence boundaries: . ! ? \n
            split_idx = -1
            boundary_char_len = 1

            for i, ch in enumerate(self.buffer):
                if ch in (".", "!", "?"):
                    if ch == "." and self._is_abbreviation(self.buffer, i):
                        continue
                    # Check for trailing quotes or brackets
                    idx = i + 1
                    while idx < len(self.buffer) and self.buffer[idx] in ('"', "'", "”", "’", ")", "]", "}"):
                        idx += 1
                    # Ensure followed by whitespace or end of buffer if followed by capital
                    if idx >= len(self.buffer) or self.buffer[idx].isspace():
                        split_idx = idx
                        break
                elif ch == "\n":
                    split_idx = i + 1
                    break
                elif ch in (",", ";", ":") and i >= self.max_clause_chars:
                    # Clause boundary splitting on long sentences to keep latency low
                    split_idx = i + 1
                    break

            if split_idx != -1:
                sentence = self.buffer[:split_idx].strip()
                self.buffer = self.buffer[split_idx:].lstrip()
                if sentence:
                    emitted.append(sentence)
            else:
                break

        return emitted

    def flush(self) -> List[str]:
        """Flush remaining text in buffer."""
        emitted: List[str] = []
        sentence = self.buffer.strip()
        self.buffer = ""
        if sentence:
            emitted.append(sentence)
        return emitted


