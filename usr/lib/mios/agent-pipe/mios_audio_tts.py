# ==============================================================================
# Validation Helpers
# ==============================================================================

def validate_engine(engine: str) -> str:
    """Validate TTS synthesis engine name."""
    engine_clean = (engine or "").strip().lower()
    if engine_clean not in SUPPORTED_ENGINES:
        raise ValueError(
            f"Unsupported engine '{engine}'. Supported engines: {', '.join(SUPPORTED_ENGINES)}"
        )
    return engine_clean


def validate_voice(voice: Optional[str], engine: str) -> str:
    """Validate voice model identifier for given engine."""
    engine_clean = validate_engine(engine)
    if not voice or not voice.strip():
        return DEFAULT_VOICES[engine_clean]

    voice_clean = voice.strip()

    # Allow custom path ending with .onnx or .bin
    if voice_clean.endswith(".onnx") or voice_clean.endswith(".bin"):
        return voice_clean

    known = KNOWN_VOICES.get(engine_clean, [])
    if voice_clean not in known:
        raise ValueError(
            f"Unsupported or invalid voice '{voice_clean}' for engine '{engine_clean}'. "
            f"Supported voices: {', '.join(known)}"
        )
    return voice_clean


def validate_text(text: str) -> str:
    """Validate input text prompt is non-empty."""
    cleaned = (text or "").strip()
    if not cleaned:
        raise ValueError("Cannot synthesize empty text prompt")
    return cleaned


