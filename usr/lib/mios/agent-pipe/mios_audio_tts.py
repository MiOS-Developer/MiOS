class AudioRingBuffer:
    """Thread-safe circular byte buffer for audio PCM streaming."""

    def __init__(self, capacity_bytes: int):
        self.capacity = max(capacity_bytes, 4096)
        self.buffer = bytearray(self.capacity)
        self.write_pos = 0
        self.read_pos = 0
        self.size = 0
        self.overflow_bytes = 0
        self.underruns = 0
        self.lock = threading.Lock()

    def write(self, data: bytes) -> int:
        """Write raw audio bytes into ring buffer."""
        if not data:
            return 0
        data_len = len(data)
        with self.lock:
            if self.size + data_len > self.capacity:
                discard = (self.size + data_len) - self.capacity
                self.overflow_bytes += discard
                self.read_pos = (self.read_pos + discard) % self.capacity
                self.size -= discard

            end_space = self.capacity - self.write_pos
            if data_len <= end_space:
                self.buffer[self.write_pos:self.write_pos + data_len] = data
            else:
                self.buffer[self.write_pos:self.capacity] = data[:end_space]
                self.buffer[0:data_len - end_space] = data[end_space:]

            self.write_pos = (self.write_pos + data_len) % self.capacity
            self.size += data_len
            return data_len

    def read(self, num_bytes: int) -> bytes:
        """Read and remove up to num_bytes from buffer."""
        with self.lock:
            read_len = min(num_bytes, self.size)
            if read_len <= 0:
                self.underruns += 1
                return b""

            end_space = self.capacity - self.read_pos
            if read_len <= end_space:
                data = bytes(self.buffer[self.read_pos:self.read_pos + read_len])
            else:
                first = self.buffer[self.read_pos:self.capacity]
                second = self.buffer[0:read_len - end_space]
                data = bytes(first + second)

            self.read_pos = (self.read_pos + read_len) % self.capacity
            self.size -= read_len
            return data

    def available(self) -> int:
        with self.lock:
            return self.size

    def clear(self) -> None:
        with self.lock:
            self.write_pos = 0
            self.read_pos = 0
            self.size = 0


class PipeWireAudioFeeder:
    """Feeds synthesized PCM audio frames into PipeWire playback buffer."""

    def __init__(
        self,
        sample_rate: int = DEFAULT_SAMPLE_RATE,
        channels: int = DEFAULT_CHANNELS,
        mock_mode: bool = False,
        dry_run: bool = False,
        output_file: Optional[str] = None,
        verbose: bool = False,
    ):
        self.sample_rate = sample_rate
        self.channels = channels
        self.mock_mode = mock_mode
        self.dry_run = dry_run
        self.output_file = output_file
        self.verbose = verbose

        capacity_bytes = int(sample_rate * DEFAULT_BUFFER_SECONDS * BYTES_PER_SAMPLE * channels)
        self.ring_buffer = AudioRingBuffer(capacity_bytes)
        self.total_bytes_written = 0
        self.total_frames_written = 0
        self.first_sound_time: Optional[float] = None
        self.feed_start_time: Optional[float] = None
        self.underruns_count = 0

        self.proc: Optional[subprocess.Popen] = None
        self.file_sink: Optional[io.BytesIO] = None
        self.is_open = False

    def log(self, msg: str) -> None:
        if self.verbose:
            print(f"[mios-audio-tts] {msg}", file=sys.stderr)

    def start(self) -> None:
        """Start audio playback stream."""
        if self.is_open:
            return
        self.feed_start_time = time.perf_counter()
        self.is_open = True

        if self.dry_run:
            self.log("PipeWireAudioFeeder started (dry-run)")
            return

        if self.output_file:
            self.file_sink = io.BytesIO()

        if not self.mock_mode:
            # Check for pw-play / paplay / aplay
            cmd = None
            if self._has_binary("pw-play"):
                cmd = [
                    "pw-play",
                    "--format", "s16le",
                    "--rate", str(self.sample_rate),
                    "--channels", str(self.channels),
                    "-",
                ]
            elif self._has_binary("paplay"):
                cmd = [
                    "paplay",
                    "--raw",
                    "--format=s16le",
                    f"--rate={self.sample_rate}",
                    f"--channels={self.channels}",
                ]
            elif self._has_binary("aplay"):
                cmd = [
                    "aplay",
                    "-q",
                    "-r", str(self.sample_rate),
                    "-f", "S16_LE",
                    "-c", str(self.channels),
                ]

            if cmd:
                try:
                    self.proc = subprocess.Popen(
                        cmd,
                        stdin=subprocess.PIPE,
                        stdout=subprocess.DEVNULL,
                        stderr=subprocess.DEVNULL,
                    )
                    self.log(f"Spawned audio playback pipeline: {' '.join(cmd)}")
                except OSError as err:
                    self.log(f"Failed to spawn audio pipeline: {err}; fallback to mock buffer")
                    self.proc = None

    def _has_binary(self, name: str) -> bool:
        return any(
            os.path.isfile(os.path.join(p, name)) and os.access(os.path.join(p, name), os.X_OK)
            for p in os.environ.get("PATH", "").split(os.pathsep)
        )

    def feed_pcm(self, pcm_bytes: bytes) -> int:
        """Feed PCM audio bytes to PipeWire buffer."""
        if not pcm_bytes:
            return 0

        now = time.perf_counter()
        if self.first_sound_time is None:
            self.first_sound_time = now

        # Alignment verification (must be even bytes for 16-bit)
        if len(pcm_bytes) % BYTES_PER_SAMPLE != 0:
            pcm_bytes = pcm_bytes[:len(pcm_bytes) - (len(pcm_bytes) % BYTES_PER_SAMPLE)]

        if not pcm_bytes:
            return 0

        # Buffer telemetry
        written = self.ring_buffer.write(pcm_bytes)
        self.total_bytes_written += written
        self.total_frames_written += written // (BYTES_PER_SAMPLE * self.channels)

        if self.output_file and self.file_sink:
            self.file_sink.write(pcm_bytes)

        if self.proc and self.proc.stdin:
            try:
                self.proc.stdin.write(pcm_bytes)
                self.proc.stdin.flush()
            except (BrokenPipeError, OSError) as err:
                self.log(f"PipeWire feed error: {err}")
                self.underruns_count += 1

        return written

    def close(self) -> None:
        """Close playback stream and flush files if required."""
        if not self.is_open:
            return
        self.is_open = False

        if self.proc:
            try:
                if self.proc.stdin:
                    self.proc.stdin.close()
                self.proc.wait(timeout=2.0)
            except Exception:
                try:
                    self.proc.kill()
                except Exception:
                    pass
            self.proc = None

        if self.output_file and self.file_sink:
            try:
                pcm_data = self.file_sink.getvalue()
                if self.output_file.lower().endswith(".wav"):
                    with wave.open(self.output_file, "wb") as wf:
                        wf.setnchannels(self.channels)
                        wf.setsampwidth(BYTES_PER_SAMPLE)
                        wf.setframerate(self.sample_rate)
                        wf.writeframes(pcm_data)
                else:
                    with open(self.output_file, "wb") as f:
                        f.write(pcm_data)
                self.log(f"Saved audio output to {self.output_file}")
            except OSError as err:
                self.log(f"Failed to write output file: {err}")

    def get_metrics(self) -> Dict[str, Any]:
        """Return feeder statistics and latency SLA metrics."""
        ttfs_ms = 0.0
        if self.first_sound_time is not None and self.feed_start_time is not None:
            ttfs_ms = round((self.first_sound_time - self.feed_start_time) * 1000.0, 2)

        return {
            "sample_rate": self.sample_rate,
            "channels": self.channels,
            "bytes_written": self.total_bytes_written,
            "frames_written": self.total_frames_written,
            "duration_sec": round(self.total_frames_written / max(self.sample_rate, 1), 2),
            "buffer_capacity_bytes": self.ring_buffer.capacity,
            "buffer_occupancy_bytes": self.ring_buffer.available(),
            "underruns": self.underruns_count + self.ring_buffer.underruns,
            "time_to_first_sound_ms": ttfs_ms,
            "target_met": ttfs_ms <= LATENCY_SLA_TARGET_MS if ttfs_ms > 0 else True,
        }


