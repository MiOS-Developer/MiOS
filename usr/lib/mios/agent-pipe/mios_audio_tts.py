def build_parser() -> argparse.ArgumentParser:
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("-v", "--verbose", action="store_true", default=argparse.SUPPRESS, help="Enable verbose diagnostic logs")
    common.add_argument("--dry-run", action="store_true", default=argparse.SUPPRESS, help="Validate configuration and parameters without executing audio")
    common.add_argument("--mock", action="store_true", default=argparse.SUPPRESS, help="Enable mock audio synthesis and playback loopback")
    common.add_argument("--sample-rate", type=int, default=argparse.SUPPRESS, help=f"Audio sample rate in Hz (default: {DEFAULT_SAMPLE_RATE})")
    common.add_argument("--engine", choices=list(SUPPORTED_ENGINES), default=argparse.SUPPRESS, help="TTS synthesis engine (piper)")
    common.add_argument("--voice", default=argparse.SUPPRESS, help="Voice model identifier")
    common.add_argument("--output", default=argparse.SUPPRESS, help="Save synthesized audio to file (.wav or raw PCM)")

    parser = argparse.ArgumentParser(
        prog="mios_audio_tts.py",
        description="Concurrent streaming Piper TTS audio synthesis and PipeWire buffer feeder (task_478, task_2711).",
        parents=[common],
    )

    subparsers = parser.add_subparsers(dest="subcommand", help="Operational modes")

    # Subcommand: stream
    stream_parser = subparsers.add_parser("stream", parents=[common], help="Stream speech synthesis from stdin, file, or socket")
    stream_parser.add_argument("--input", "-i", default="-", help="Input text path or '-' for stdin (default: -)")
    stream_parser.add_argument("--socket", default=None, help="Unix domain socket path to bind for streaming")
    stream_parser.add_argument("--timeout", type=float, default=None, help="Timeout in seconds for daemon operation")

    # Subcommand: speak
    speak_parser = subparsers.add_parser("speak", parents=[common], help="One-shot speech synthesis of text argument")
    speak_parser.add_argument("text", help="Text prompt to synthesize into audio")

    # Subcommand: status
    subparsers.add_parser("status", parents=[common], help="Report TTS engine connection, buffer stats, and voice models")

    return parser


def main() -> int:
    parser = build_parser()
    args = parser.parse_args()

    if not args.subcommand:
        parser.print_help()
        return 0

    verbose = getattr(args, "verbose", False)
    dry_run = getattr(args, "dry_run", False)
    mock_mode = getattr(args, "mock", False)
    sample_rate = getattr(args, "sample_rate", DEFAULT_SAMPLE_RATE)
    raw_engine = getattr(args, "engine", "piper")
    raw_voice = getattr(args, "voice", None)
    output_file = getattr(args, "output", None)

    try:
        engine = validate_engine(raw_engine)
        voice = validate_voice(raw_voice, engine)
    except ValueError as err:
        print(f"Error: {err}", file=sys.stderr)
        return 1

    if args.subcommand == "status":
        worker = StreamingTTSWorker(
            engine=engine,
            voice=voice,
            sample_rate=sample_rate,
            mock_mode=mock_mode,
            dry_run=dry_run,
            verbose=verbose,
        )
        status_data = worker.get_status()
        print(json.dumps(status_data, indent=2))
        return 0

    elif args.subcommand == "speak":
        try:
            cleaned_text = validate_text(args.text)
        except ValueError as err:
            print(f"Error: {err}", file=sys.stderr)
            return 1

        if dry_run:
            print("[mios-audio-tts] Dry-run validated: speak command parameters OK")
            print(f"  Engine: {engine}")
            print(f"  Voice: {voice}")
            print(f"  Text: '{cleaned_text}'")
            print(f"  Mock mode: {mock_mode}")
            return 0

        worker = StreamingTTSWorker(
            engine=engine,
            voice=voice,
            sample_rate=sample_rate,
            mock_mode=mock_mode,
            dry_run=dry_run,
            output_file=output_file,
            verbose=verbose,
        )
        try:
            status = worker.speak(cleaned_text)
            if verbose:
                print(f"[mios-audio-tts] Synthesis complete: {json.dumps(status)}", file=sys.stderr)
            return 0
        except Exception as err:
            print(f"Error during speech synthesis: {err}", file=sys.stderr)
            return 1

    elif args.subcommand == "stream":
        if dry_run:
            print("[mios-audio-tts] Dry-run validated: stream command parameters OK")
            print(f"  Engine: {engine}")
            print(f"  Voice: {voice}")
            print(f"  Input: {args.input}")
            print(f"  Socket: {args.socket}")
            print(f"  Mock mode: {mock_mode}")
            return 0

        worker = StreamingTTSWorker(
            engine=engine,
            voice=voice,
            sample_rate=sample_rate,
            mock_mode=mock_mode,
            dry_run=dry_run,
            output_file=output_file,
            verbose=verbose,
        )

        if args.socket:
            worker.stream_from_socket(sock_path=args.socket, timeout=args.timeout)
            return 0
        else:
            # Read from file or stdin
            def token_generator() -> Generator[str, None, None]:
                if args.input == "-":
                    for line in sys.stdin:
                        yield line
                else:
                    if not os.path.exists(args.input):
                        raise FileNotFoundError(f"Input file not found: {args.input}")
                    with open(args.input, "r", encoding="utf-8") as f:
                        for line in f:
                            yield line

            try:
                status = worker.stream_from_iterable(token_generator())
                if verbose:
                    print(f"[mios-audio-tts] Stream complete: {json.dumps(status)}", file=sys.stderr)
                return 0
            except Exception as err:
                print(f"Error during streaming synthesis: {err}", file=sys.stderr)
                return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
