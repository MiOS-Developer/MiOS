class StreamingTTSWorker:
    """Coordinates text streaming, sentence splitting, concurrent synthesis, and PipeWire feeding."""

    def __init__(
        self,
        engine: str = "piper",
        voice: Optional[str] = None,
        sample_rate: int = DEFAULT_SAMPLE_RATE,
        mock_mode: bool = False,
        dry_run: bool = False,
        output_file: Optional[str] = None,
        verbose: bool = False,
        piper_url: str = DEFAULT_PIPER_URL,
    ):
        self.engine = validate_engine(engine)
        self.voice = validate_voice(voice, self.engine)
        self.sample_rate = sample_rate
        self.mock_mode = mock_mode
        self.dry_run = dry_run
        self.output_file = output_file
        self.verbose = verbose

        self.chunker = SentenceChunker()
        self.feeder = PipeWireAudioFeeder(
            sample_rate=sample_rate,
            channels=DEFAULT_CHANNELS,
            mock_mode=mock_mode,
            dry_run=dry_run,
            output_file=output_file,
            verbose=verbose,
        )

        if mock_mode or dry_run:
            self.synthesis_engine: BaseSynthesisEngine = MockSynthesisEngine(sample_rate=sample_rate)
        else:
            self.synthesis_engine = HttpSynthesisEngine(
                endpoint_url=piper_url,
                engine=self.engine,
                sample_rate=sample_rate,
                verbose=verbose,
            )

        self.executor = concurrent.futures.ThreadPoolExecutor(max_workers=4)
        self.pending_futures: List[Tuple[int, str, concurrent.futures.Future]] = []
        self.chunk_index = 0
        self.running = False

    def log(self, msg: str) -> None:
        if self.verbose:
            print(f"[mios-audio-tts] {msg}", file=sys.stderr)

    def _submit_sentence(self, sentence: str) -> None:
        """Submit sentence chunk to concurrent synthesis worker."""
        if not sentence.strip():
            return

        idx = self.chunk_index
        self.chunk_index += 1
        self.log(f"Submitting chunk {idx} for synthesis: '{sentence}'")

        future = self.executor.submit(
            self.synthesis_engine.synthesize_chunk,
            sentence,
            self.voice,
        )
        self.pending_futures.append((idx, sentence, future))

    def _drain_ready_audio(self, wait_all: bool = False) -> int:
        """Drain synthesized audio chunks in sequential order and feed to PipeWire."""
        fed_chunks = 0
        while self.pending_futures:
            idx, sentence, future = self.pending_futures[0]
            if wait_all or future.done():
                self.pending_futures.pop(0)
                try:
                    pcm_data = future.result()
                    self.feeder.feed_pcm(pcm_data)
                    fed_chunks += 1
                    self.log(f"Fed chunk {idx} ({len(pcm_data)} bytes) to audio buffer")
                except Exception as err:
                    self.log(f"Synthesis failed for chunk {idx}: {err}")
                    if not self.mock_mode:
                        raise
            else:
                break
        return fed_chunks

    def feed_token(self, token: str) -> int:
        """Feed incremental text token from LLM or socket."""
        sentences = self.chunker.feed(token)
        for s in sentences:
            self._submit_sentence(s)

        return self._drain_ready_audio(wait_all=False)

    def flush(self) -> int:
        """Flush remaining text buffer and wait for all synthesis tasks to complete."""
        remaining = self.chunker.flush()
        for s in remaining:
            self._submit_sentence(s)

        return self._drain_ready_audio(wait_all=True)

    def speak(self, text: str) -> Dict[str, Any]:
        """Perform one-shot speech synthesis of text prompt."""
        cleaned_text = validate_text(text)
        self.feeder.start()
        try:
            self.feed_token(cleaned_text)
            self.flush()
        finally:
            self.feeder.close()

        return self.get_status()

    def stream_from_iterable(self, token_iter: Iterable[str]) -> Dict[str, Any]:
        """Stream speech synthesis from token iterable."""
        self.feeder.start()
        try:
            for token in token_iter:
                self.feed_token(token)
            self.flush()
        finally:
            self.feeder.close()

        return self.get_status()

    def stream_from_socket(self, sock_path: str = DEFAULT_SOCKET_PATH, timeout: Optional[float] = None) -> None:
        """Run Unix domain socket listener for incoming streaming text tokens."""
        sock_dir = os.path.dirname(sock_path)
        if sock_dir and not os.path.exists(sock_dir):
            try:
                os.makedirs(sock_dir, exist_ok=True)
            except OSError:
                sock_path = f"/tmp/audio-tts-{os.getuid()}.sock"

        if os.path.exists(sock_path):
            try:
                os.unlink(sock_path)
            except OSError:
                pass

        server_sock = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        server_sock.bind(sock_path)
        server_sock.listen(5)
        server_sock.setblocking(False)
        self.log(f"Listening for text streams on {sock_path}")

        self.running = True

        def sig_handler(sig, frame):
            self.running = False

        if threading.current_thread() is threading.main_thread():
            try:
                signal.signal(signal.SIGINT, sig_handler)
                signal.signal(signal.SIGTERM, sig_handler)
            except (ValueError, AttributeError):
                pass

        start_time = time.time()
        clients: List[socket.socket] = []

        try:
            while self.running:
                if timeout and (time.time() - start_time) >= timeout:
                    break

                readable, _, _ = select.select([server_sock] + clients, [], [], 0.05)
                for s in readable:
                    if s is server_sock:
                        client, _ = server_sock.accept()
                        client.setblocking(False)
                        clients.append(client)
                        self.feeder.start()
                        self.log("Accepted text streaming client")
                    else:
                        try:
                            data = s.recv(4096)
                            if not data:
                                clients.remove(s)
                                s.close()
                                self.flush()
                                continue
                            text = data.decode("utf-8", errors="replace")
                            self.feed_token(text)
                        except (BlockingIOError, ConnectionResetError):
                            if s in clients:
                                clients.remove(s)
                                s.close()
        finally:
            for c in clients:
                try:
                    c.close()
                except Exception:
                    pass
            try:
                server_sock.close()
                if os.path.exists(sock_path):
                    os.unlink(sock_path)
            except Exception:
                pass
            self.feeder.close()

    def get_status(self) -> Dict[str, Any]:
        """Return comprehensive engine status, buffer statistics, and latency SLA."""
        feeder_metrics = self.feeder.get_metrics()
        return {
            "engine": self.engine,
            "voice": self.voice,
            "supported_engines": list(SUPPORTED_ENGINES),
            "supported_voices": KNOWN_VOICES.get(self.engine, []),
            "mock_mode": self.mock_mode,
            "dry_run": self.dry_run,
            "chunks_synthesized": self.chunk_index,
            "latency_sla_target_ms": LATENCY_SLA_TARGET_MS,
            **feeder_metrics,
            "status": "healthy" if feeder_metrics["underruns"] == 0 else "degraded",
        }


