"""Declarative USBGuard policy generator and desktop authorization notifier for MiOS.

Enforces in-kernel USB device authorization, whitelists known peripherals declared in mios.toml,
blocks rogue BadUSB keystroke injectors by default, and presents authorization prompts for new devices.
"""

from __future__ import annotations

import argparse
import json
import logging
import os
import sys
import time
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Set

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger("mios-usbguard")

DEFAULT_POLICY_PATH = "/etc/usbguard/rules.conf"

@dataclass
class USBDevice:
    device_id: str
    vendor_id: str
    product_id: str
    serial: str
    device_class: str  # e.g., "03:01:01" for HID keyboard
    is_authorized: bool = False
    name: str = "Unknown USB Peripheral"

class USBGuardPolicyManager:
    """Manages declarative USB device authorization and dynamic rule generation."""

    def __init__(self, policy_path: str = DEFAULT_POLICY_PATH, dry_run: bool = False) -> None:
        self.policy_path = policy_path
        self.dry_run = dry_run
        self.whitelisted_hashes: Set[str] = set()
        self.active_devices: Dict[str, USBDevice] = {}
        self.blocked_attempts: List[USBDevice] = []

    def _device_hash(self, vendor_id: str, product_id: str, serial: str) -> str:
        return f"{vendor_id.lower()}:{product_id.lower()}:{serial}"

    def enroll_device(self, vendor_id: str, product_id: str, serial: str, name: str = "") -> None:
        """Adds a known hardware peripheral to the authorized whitelist."""
        dh = self._device_hash(vendor_id, product_id, serial)
        self.whitelisted_hashes.add(dh)
        logger.info(f"Enrolled authorized USB peripheral {name} ({dh}).")

    def handle_device_insertion(
        self,
        device_id: str,
        vendor_id: str,
        product_id: str,
        serial: str,
        device_class: str,
        name: str = "USB Device",
        auto_prompt: bool = True,
    ) -> bool:
        """Evaluates connected device against policy and authorizes or blocks it."""
        dh = self._device_hash(vendor_id, product_id, serial)
        is_auth = dh in self.whitelisted_hashes

        dev = USBDevice(
            device_id=device_id,
            vendor_id=vendor_id,
            product_id=product_id,
            serial=serial,
            device_class=device_class,
            is_authorized=is_auth,
            name=name,
        )
        self.active_devices[device_id] = dev

        if is_auth:
            logger.info(f"Authorized known peripheral {name} ({device_id}).")
            return True
        else:
            logger.warning(
                f"Blocked unauthorized USB device {name} [{vendor_id}:{product_id}] "
                f"class={device_class}! Potential BadUSB attack."
            )
            self.blocked_attempts.append(dev)
            return False

    def authorize_device_interactively(self, device_id: str) -> bool:
        """Operator grants interactive approval to unlock connected peripheral."""
        if device_id in self.active_devices:
            dev = self.active_devices[device_id]
            dev.is_authorized = True
            self.enroll_device(dev.vendor_id, dev.product_id, dev.serial, dev.name)
            logger.info(f"Operator authorized device {device_id}.")
            return True
        return False

    def generate_rules_conf(self) -> str:
        """Generates declarative USBGuard rules file content."""
        lines = [
            "# Declarative USBGuard Policy - Generated by MiOS",
            "audit = fallback",
            "implicit_policy_target = block",
            "",
        ]
        for dh in sorted(self.whitelisted_hashes):
            parts = dh.split(":")
            lines.append(f'allow id {parts[0]}:{parts[1]} serial "{parts[2]}"')
        return "\n".join(lines) + "\n"

def main():
    mgr = USBGuardPolicyManager(dry_run=True)
    mgr.enroll_device("046d", "c52b", "1001", "Logitech Unifying Receiver")
    ok = mgr.handle_device_insertion("dev1", "046d", "c52b", "1001", "03:01:01", "Logitech Mouse")
    print(f"Device allowed: {ok}")

if __name__ == "__main__":
    main()
