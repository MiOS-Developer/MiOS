// AI-hint: `mios-gen render-usb-storage` -- renders usr/lib/udev/rules.d/99-mios-usb-storage-power.rules from [hardware.storage_link].usb_storage_autosuspend: false keeps every USB mass-storage device (BOT or UAS interface) at power/control=on so the disk under root, swap or the journal is never runtime-suspended; true renders a rule file with no rule. --check fails on a stale or hand-edited rule file.
// AI-related: usr/share/mios/mios.toml, usr/lib/udev/rules.d/99-mios-usb-storage-power.rules, src/mios-rs/mios-probe/src/storage.rs
use std::fs;
use std::path::Path;

use toml::Value;

pub const OUTPUT: &str = "usr/lib/udev/rules.d/99-mios-usb-storage-power.rules";

/// [hardware.storage_link].usb_storage_autosuspend, required.
pub fn autosuspend(data: &Value) -> Result<bool, String> {
    data.get("hardware")
        .and_then(|h| h.get("storage_link"))
        .and_then(|s| s.get("usb_storage_autosuspend"))
        .and_then(Value::as_bool)
        .ok_or_else(|| {
            "hardware.storage_link.usb_storage_autosuspend must be a boolean".to_string()
        })
}

pub fn render(autosuspend: bool) -> String {
    let mut out = String::from(
        "# AI-hint: GENERATED by `mios-gen render-usb-storage` from mios.toml [hardware.storage_link].usb_storage_autosuspend -- do not edit; edit the SSOT.\n\
         # AI-related: usr/share/mios/mios.toml, tools/native/mios-gen/src/usb_storage.rs\n",
    );
    if autosuspend {
        out.push_str("# usb_storage_autosuspend = true: USB mass-storage devices keep the kernel's runtime-PM default.\n");
    } else {
        out.push_str(
            "# usb_storage_autosuspend = false: a USB device exposing a mass-storage interface\n\
             # (class 08, subclass 06: bulk-only 50 or UAS 62) is never runtime-suspended, so a\n\
             # disk carrying root, swap or the journal cannot be put to sleep under load.\n\
             # ID_USB_INTERFACES comes from the usb_id builtin in 50-udev-default.rules.\n\
             ACTION==\"add|bind\", SUBSYSTEM==\"usb\", ENV{DEVTYPE}==\"usb_device\", ENV{ID_USB_INTERFACES}==\"*:0806[56]?:*\", TEST==\"power/control\", ATTR{power/control}=\"on\"\n",
        );
    }
    out
}

/// Write (or with `check`, compare) the rule under `root`; Ok(changed).
pub fn run(root: &Path, check: bool) -> Result<bool, String> {
    let ssot = root.join("usr/share/mios/mios.toml");
    let data: Value =
        toml::from_str(&fs::read_to_string(&ssot).map_err(|e| format!("{}: {e}", ssot.display()))?)
            .map_err(|e| format!("{}: {e}", ssot.display()))?;
    let want = render(autosuspend(&data)?);
    let out = root.join(OUTPUT);
    if fs::read_to_string(&out).ok().as_deref() == Some(want.as_str()) {
        return Ok(false);
    }
    if check {
        return Err(format!(
            "{OUTPUT} is stale against mios.toml -- run mios-gen render-usb-storage"
        ));
    }
    if let Some(parent) = out.parent() {
        fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }
    fs::write(&out, want).map_err(|e| format!("{}: {e}", out.display()))?;
    Ok(true)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn root_with(ssot: &str) -> tempfile::TempDir {
        let d = tempfile::tempdir().unwrap();
        fs::create_dir_all(d.path().join("usr/share/mios")).unwrap();
        fs::write(d.path().join("usr/share/mios/mios.toml"), ssot).unwrap();
        d
    }

    #[test]
    fn false_keeps_usb_storage_awake() {
        let rule = render(false);
        let lines: Vec<_> = rule.lines().filter(|l| !l.starts_with('#')).collect();
        assert_eq!(lines.len(), 1, "{rule}");
        for want in [
            "SUBSYSTEM==\"usb\"",
            "ENV{DEVTYPE}==\"usb_device\"",
            "ENV{ID_USB_INTERFACES}==\"*:0806[56]?:*\"",
            "ATTR{power/control}=\"on\"",
        ] {
            assert!(lines[0].contains(want), "{want} missing: {}", lines[0]);
        }
    }

    #[test]
    fn true_renders_no_rule() {
        assert!(render(true).lines().all(|l| l.starts_with('#')));
    }

    #[test]
    fn the_rule_follows_the_ssot_value() {
        for (value, rule_lines) in [(false, 1), (true, 0)] {
            let d = root_with(&format!(
                "[hardware.storage_link]\nusb_storage_autosuspend = {value}\n"
            ));
            assert!(run(d.path(), false).unwrap());
            let text = fs::read_to_string(d.path().join(OUTPUT)).unwrap();
            assert_eq!(
                text.lines().filter(|l| !l.starts_with('#')).count(),
                rule_lines
            );
            assert!(!run(d.path(), true).unwrap(), "check after write");
        }
    }

    #[test]
    fn missing_key_and_hand_edits_fail_the_gate() {
        let d = root_with("[hardware.storage_link]\ncritical_roles = []\n");
        assert!(run(d.path(), true)
            .unwrap_err()
            .contains("usb_storage_autosuspend"));
        let d = root_with("[hardware.storage_link]\nusb_storage_autosuspend = \"no\"\n");
        assert!(run(d.path(), false).is_err(), "a non-boolean was accepted");
        let d = root_with("[hardware.storage_link]\nusb_storage_autosuspend = false\n");
        assert!(
            run(d.path(), true).is_err(),
            "a missing rule passed --check"
        );
        run(d.path(), false).unwrap();
        // A literal planted by hand (here: autosuspend allowed) is stale.
        let path = d.path().join(OUTPUT);
        let planted = fs::read_to_string(&path)
            .unwrap()
            .replace("=\"on\"", "=\"auto\"");
        fs::write(&path, planted).unwrap();
        assert!(run(d.path(), true).unwrap_err().contains("stale"));
    }

    #[test]
    fn the_shipped_rule_matches_the_shipped_ssot() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../..");
        assert!(!run(&root, true).unwrap(), "{OUTPUT} is stale");
    }
}
