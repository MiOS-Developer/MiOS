fn managed_values(g: &Grub, fonts_on: bool) -> Vec<(&'static str, String)> {
    let mut v = vec![
        ("GRUB_TIMEOUT", g.timeout_s.to_string()),
        ("GRUB_TIMEOUT_STYLE", g.timeout_style.clone()),
        ("GRUB_DEFAULT", "saved".to_string()),
        ("GRUB_SAVEDEFAULT", (g.default == "last").to_string()),
        ("GRUB_DISABLE_SUBMENU", "true".to_string()),
        ("GRUB_DISABLE_RECOVERY", "\"true\"".to_string()),
        ("GRUB_ENABLE_BLSCFG", "true".to_string()),
        // grub2-mkconfig would otherwise rewrite every BLS options line from GRUB_CMDLINE_LINUX,
        // erasing the per-GPU kernel arguments of the managed entries.
        ("GRUB_GRUBENV_UPDATE", "no".to_string()),
        ("GRUB_DISABLE_OS_PROBER", "true".to_string()),
        // Without convertible fonts GRUB draws its embedded 16 px Unifont; a lower mode makes it readable.
        ("GRUB_GFXMODE", format!("\"{}\"", if g.theme.enabled && !fonts_on { &g.theme.builtin_font_gfxmode } else { &g.gfxmode })),
        ("GRUB_GFXPAYLOAD_LINUX", "keep".to_string()),
    ];
    if g.theme.enabled {
        v.push(("GRUB_TERMINAL_OUTPUT", "\"gfxterm\"".to_string()));
        v.push(("GRUB_THEME", format!("\"{}/theme.txt\"", g.theme.dir)));
    } else {
        v.push(("GRUB_TERMINAL_OUTPUT", "\"console\"".to_string()));
    }
    v
}

/// Keep every host line of /etc/default/grub (GRUB_CMDLINE_LINUX, GRUB_DISTRIBUTOR, ...), drop the managed keys
/// wherever they are, and append one managed block. Idempotent.
pub fn render_default_grub(old: &str, g: &Grub, fonts_on: bool) -> String {
    let mut out: Vec<String> = Vec::new();
    let mut in_block = false;
    for line in old.lines() {
        if line == BEGIN {
            in_block = true;
            continue;
        }
        if in_block {
            if line == END {
                in_block = false;
            }
            continue;
        }
        let trimmed = line.trim_start();
        if RETIRED_COMMENTS.contains(&line.trim()) {
            continue;
        }
        if !trimmed.starts_with('#') {
            if let Some((key, _)) = trimmed.split_once('=') {
                let key = key.trim().trim_start_matches("export ").trim();
                if MANAGED_KEYS.contains(&key) {
                    continue;
                }
            }
        }
        out.push(line.to_string());
    }
    while out.last().is_some_and(|l| l.trim().is_empty()) {
        out.pop();
    }
    out.push(String::new());
    out.push(BEGIN.to_string());
    for (k, v) in managed_values(g, fonts_on) {
        out.push(format!("{k}={v}"));
    }
    out.push(END.to_string());
    out.join("\n") + "\n"
}

pub fn parse_entry(text: &str) -> Result<Entry, String> {
    let mut linux = Vec::new();
    let mut initrd = Vec::new();
    let mut options = Vec::new();
    for l in text.lines() {
        let l = l.trim();
        let (key, rest) = l.split_once(char::is_whitespace).unwrap_or((l, ""));
        let rest = rest.trim();
        match key {
            "linux" => linux.push(rest.to_string()),
            "initrd" => initrd.extend(rest.split_whitespace().map(str::to_string)),
            "options" => options.extend(rest.split_whitespace().map(str::to_string)),
            "efi" => return Err("UKI (efi) boot entries are not supported".into()),
            _ => {}
        }
    }
    if linux.len() != 1 || linux[0].is_empty() {
        return Err("boot entry needs exactly one linux line".into());
    }
    if initrd.is_empty() {
        return Err("boot entry has no initrd".into());
    }
    Ok(Entry { linux: linux.remove(0), initrd, options })
}

fn entry_files_exist(boot: &Path, e: &Entry) -> bool {
    std::iter::once(&e.linux)
        .chain(e.initrd.iter())
        .filter(|p| !p.starts_with('$'))
        .all(|p| boot.join(p.trim_start_matches('/')).is_file())
}

pub fn recovery_options(g: &Grub, profile_options: &[String]) -> Result<Vec<String>, String> {
    let removed = |o: &str| {
        g.recovery_remove.iter().any(|r| if r.ends_with('=') { o.starts_with(r.as_str()) } else { o == r })
    };
    let mut out: Vec<String> =
        profile_options.iter().filter(|o| !o.starts_with('$') && !removed(o)).cloned().collect();
    for a in &g.recovery_append {
        if !out.contains(a) {
            out.push(a.clone());
        }
    }
    for o in &out {
        safe("recovery kernel option", o)?;
    }
    Ok(out)
}

fn grub_fs_module(fs_type: &str) -> Result<&'static str, String> {
    match fs_type {
        "xfs" => Ok("xfs"),
        "ext2" | "ext3" | "ext4" => Ok("ext2"),
        "btrfs" => Ok("btrfs"),
        "vfat" => Ok("fat"),
        other => Err(format!("unsupported /boot filesystem {other:?}")),
    }
}

pub fn render_recovery(
    g: &Grub,
    boot_uuid: &str,
    fs_type: &str,
    linux: &str,
    initrd: &[String],
    options: &[String],
) -> Result<String, String> {
    if boot_uuid.is_empty() || !boot_uuid.bytes().all(|c| c.is_ascii_hexdigit() || c == b'-') {
        return Err(format!("invalid /boot filesystem UUID {boot_uuid:?}"));
    }
    boot_path("recovery kernel", linux)?;
    for i in initrd {
        boot_path("recovery initrd", i)?;
    }
    let module = grub_fs_module(fs_type)?;
    let mut s = String::new();
    s.push_str("#!/usr/bin/sh\n");
    s.push_str(HINT);
    s.push_str("\n# A static entry: recovery stays in the menu even when BLS discovery fails.\n");
    s.push_str("exec tail -n +5 \"$0\"\n");
    s.push_str(&format!("menuentry '{}' --class mios --unrestricted --id {RECOVERY_ID} {{\n", g.recovery_title));
    if g.recovery_saves_default {
        s.push_str("\tsavedefault\n");
    }
    s.push_str("\tinsmod part_gpt\n");
    s.push_str(&format!("\tinsmod {module}\n"));
    s.push_str(&format!("\tsearch --no-floppy --fs-uuid --set=root {boot_uuid}\n"));
    s.push_str(&format!("\tlinux {linux} {}\n", options.join(" ")));
    s.push_str(&format!("\tinitrd {}\n", initrd.join(" ")));
    s.push_str("}\n");
    Ok(s)
}

pub fn render_kernel_hook() -> String {
    format!(
        "#!/usr/bin/sh\n{HINT}\n# kernel-install adapter: the boot-menu policy (managed GPU entries follow the newest kernel, other\n# entries archived, default kept valid) lives in mios-gen. A failure never fails the kernel transaction.\ncase \"$1\" in\nadd|remove)\n\t/usr/bin/mios-gen render-grub --apply --kernel-event \"$1\" --kernel-version \"$2\" ||\n\t\techo \"mios: GRUB menu maintenance failed; run: sudo mios-gen render-grub --apply\" >&2\n\t;;\nesac\nexit 0\n"
    )
}

/// Names (in /boot/loader/entries) that leave the menu. Refuses when a managed entry is missing, so the menu can
/// never be emptied.
pub fn plan_archive(names: &[String], g: &Grub) -> Result<Vec<String>, String> {
    for p in &g.menu_profiles {
        if !names.contains(&managed_entry(p)) {
            return Err(format!(
                "managed boot entry {} is missing; refusing to archive the other entries (run render-hyprland --boot-entry first)",
                managed_entry(p)
            ));
        }
    }
    let keep: Vec<String> = g.menu_profiles.iter().map(|p| managed_entry(p)).collect();
    Ok(names.iter().filter(|n| n.ends_with(".conf") && !keep.contains(n)).cloned().collect())
}

/// grub2-editenv set/unset lists that make grubenv match the SSOT.
pub fn env_plan(g: &Grub, env: &[(String, String)], booted: Option<&str>) -> (Vec<String>, Vec<String>) {
    let get = |k: &str| env.iter().find(|(a, _)| a == k).map(|(_, v)| v.as_str());
    let mut set = Vec::new();
    let mut unset = Vec::new();
    for k in ["blsdir", "menu_auto_hide"] {
        if get(k).is_some() {
            unset.push(k.to_string());
        }
    }
    let mut valid = g.managed_ids();
    if g.recovery && g.recovery_saves_default {
        valid.push(RECOVERY_ID.to_string());
    }
    if g.default == "last" {
        if get("save_default") != Some("true") {
            set.push("save_default=true".to_string());
        }
        let saved = get("saved_entry").unwrap_or("");
        if !valid.iter().any(|v| v == saved) {
            let p = booted
                .filter(|b| g.menu_profiles.iter().any(|m| m == b))
                .unwrap_or(g.initial_default.as_str());
            set.push(format!("saved_entry=mios-desktop-{p}"));
        }
    } else {
        if get("save_default").is_some() {
            unset.push("save_default".to_string());
        }
        let want = format!("mios-desktop-{}", g.default);
        if get("saved_entry") != Some(want.as_str()) {
            set.push(format!("saved_entry={want}"));
        }
    }
    if let Some(next) = get("next_entry") {
        if !next.is_empty() && !valid.iter().any(|v| v == next) {
            unset.push("next_entry".to_string());
        }
    }
    (set, unset)
}

/// The full font name stored in a PFF2 file's NAME section (what a GRUB theme must reference).
pub fn pf2_name(bytes: &[u8]) -> Result<String, String> {
    let mut i = 0usize;
    while i + 8 <= bytes.len() {
        let tag = &bytes[i..i + 4];
        let len = u32::from_be_bytes([bytes[i + 4], bytes[i + 5], bytes[i + 6], bytes[i + 7]]) as usize;
        let start = i + 8;
        if tag == b"CHIX" || tag == b"DATA" || start.checked_add(len).is_none_or(|end| end > bytes.len()) {
            break;
        }
        if tag == b"NAME" {
            let raw = &bytes[start..start + len];
            let name = raw.split(|b| *b == 0).next().unwrap_or(&[]);
            return String::from_utf8(name.to_vec()).map_err(|e| e.to_string());
        }
        i = start + len;
    }
    Err("PFF2 font has no NAME section".into())
}

