// AI-hint: render-flatpak-overrides -- projects mios.toml [flatpak.overrides.global] into the system-wide Flatpak override
// keyfile var/lib/flatpak/overrides/global ([Context] filesystems, [Session Bus Policy] talk names, [Environment] values
// read from the SSOT keys named in environment_from). The file is generated; --check reports drift without writing.
// AI-related: usr/share/mios/mios.toml [flatpak.overrides.global], var/lib/flatpak/overrides/global, src/mios-rs/miosd/src/appmenu.rs
use std::fs;
use std::path::Path;
use toml_edit::{Document, Item, Value};

pub const OUTPUT: &str = "var/lib/flatpak/overrides/global";
const HEADER: &str = "# Generated by mios-gen render-flatpak-overrides from mios.toml [flatpak.overrides.global]; edit the SSOT.\n";

fn strings(item: Option<&Item>, key: &str) -> Result<Vec<String>, String> {
    let Some(item) = item else { return Ok(Vec::new()) };
    let array = item.as_array().ok_or(format!("[flatpak.overrides.global] {key} must be an array of strings"))?;
    array
        .iter()
        .map(|v| {
            v.as_str()
                .filter(|s| !s.is_empty() && !s.contains([';', '\n', '\r', '=', '[', ']']))
                .map(str::to_owned)
                .ok_or(format!("[flatpak.overrides.global] {key}: entries must be nonempty and free of ; = [ ] and newlines"))
        })
        .collect()
}

/// A D-Bus well-known name (the only kind a Session Bus Policy may name): >= 2 dot-separated elements of
/// [A-Za-z0-9_-], no element starting with a digit, <= 255 bytes; a trailing ".*" wildcard element is allowed.
fn bus_name(s: &str) -> bool {
    let body = s.strip_suffix(".*").unwrap_or(s);
    s.len() <= 255
        && body.split('.').count() >= if body.len() < s.len() { 1 } else { 2 }
        && body.split('.').all(|e| {
            !e.is_empty()
                && !e.starts_with(|c: char| c.is_ascii_digit())
                && e.chars().all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-')
        })
}

fn lookup<'a>(doc: &'a Document, dotted: &str) -> Option<&'a Value> {
    let mut parts = dotted.split('.');
    let mut item = doc.get(parts.next()?)?;
    for p in parts {
        item = item.get(p)?;
    }
    item.as_value()
}

pub fn render(toml_text: &str) -> Result<String, String> {
    let doc: Document = toml_text.parse().map_err(|e| format!("mios.toml: {e}"))?;
    let g = doc
        .get("flatpak")
        .and_then(|f| f.get("overrides"))
        .and_then(|o| o.get("global"))
        .ok_or("[flatpak.overrides.global] is not declared")?;
    let mut out = String::from(HEADER);
    let fs_list = strings(g.get("filesystems"), "filesystems")?;
    if !fs_list.is_empty() {
        out += "[Context]\nfilesystems=";
        for f in &fs_list {
            out += f;
            out.push(';');
        }
        out += "\n";
    }
    let talk = strings(g.get("session_bus_talk"), "session_bus_talk")?;
    if let Some(bad) = talk.iter().find(|n| !bus_name(n)) {
        return Err(format!("[flatpak.overrides.global] session_bus_talk: {bad:?} is not a D-Bus well-known name"));
    }
    if !talk.is_empty() {
        out += "\n[Session Bus Policy]\n";
        for n in &talk {
            out += &format!("{n}=talk\n");
        }
    }
    if let Some(env) = g.get("environment_from") {
        let env = env.as_table_like().ok_or("[flatpak.overrides.global.environment_from] must be a table")?;
        let mut lines = String::new();
        for (var, src) in env.iter() {
            if var.is_empty() || !var.chars().all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || c == '_') {
                return Err(format!("environment_from: {var:?} is not an environment variable name"));
            }
            let key = src.as_str().ok_or(format!("environment_from.{var} must name an SSOT key"))?;
            let value = match lookup(&doc, key).ok_or(format!("environment_from.{var}: SSOT key {key} is not set"))? {
                Value::String(s) => s.value().clone(),
                Value::Integer(i) => i.value().to_string(),
                Value::Boolean(b) => b.value().to_string(),
                _ => return Err(format!("environment_from.{var}: {key} must be a string, integer or boolean")),
            };
            if value.contains(['\n', '\r']) {
                return Err(format!("environment_from.{var}: {key} contains a newline"));
            }
            lines += &format!("{var}={value}\n");
        }
        if !lines.is_empty() {
            out += "\n[Environment]\n";
            out += &lines;
        }
    }
    Ok(out)
}

pub fn run(root: &Path, check: bool) -> Result<String, (String, i32)> {
    let toml_path = root.join("usr/share/mios/mios.toml");
    let text = fs::read_to_string(&toml_path).map_err(|e| (format!("render-flatpak-overrides: {}: {e}", toml_path.display()), 1))?;
    let body = render(&text).map_err(|e| (format!("render-flatpak-overrides: {e}"), 1))?;
    let path = root.join(OUTPUT);
    if fs::read_to_string(&path).ok().as_deref() == Some(body.as_str()) {
        return Ok(format!("[render-flatpak-overrides] {OUTPUT} matches"));
    }
    if check {
        return Err((format!("[render-flatpak-overrides] DRIFT: {OUTPUT} -- regenerate with mios-gen render-flatpak-overrides"), 1));
    }
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir).map_err(|e| (format!("render-flatpak-overrides: {}: {e}", dir.display()), 1))?;
    }
    let tmp = path.with_extension("mios-new");
    fs::write(&tmp, &body).and_then(|_| fs::rename(&tmp, &path)).map_err(|e| (format!("render-flatpak-overrides: {}: {e}", path.display()), 1))?;
    Ok(format!("[render-flatpak-overrides] {OUTPUT} rendered"))
}

#[cfg(test)]
mod tests {
    use super::*;

    const SSOT: &str = "[appearance]\ngtk_theme = \"adw-gtk3-dark\"\ncursor_size = 24\n\
        [flatpak.overrides.global]\nfilesystems = [\"xdg-config/gtk-4.0:ro\", \"!/usr/share/icons\"]\n\
        session_bus_talk = [\"com.canonical.AppMenu.Registrar\"]\n\
        [flatpak.overrides.global.environment_from]\nGTK_THEME = \"appearance.gtk_theme\"\nXCURSOR_SIZE = \"appearance.cursor_size\"\n";

    #[test]
    fn renders_context_bus_policy_and_environment_from_the_ssot() {
        let out = render(SSOT).unwrap();
        assert_eq!(
            out,
            format!("{HEADER}[Context]\nfilesystems=xdg-config/gtk-4.0:ro;!/usr/share/icons;\n\n[Session Bus Policy]\ncom.canonical.AppMenu.Registrar=talk\n\n[Environment]\nGTK_THEME=adw-gtk3-dark\nXCURSOR_SIZE=24\n")
        );
    }

    #[test]
    fn the_vendor_ssot_lets_every_sandboxed_app_reach_the_menu_exporter() {
        let text = fs::read_to_string(Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../usr/share/mios/mios.toml")).unwrap();
        let out = render(&text).unwrap();
        assert!(out.contains("\n[Session Bus Policy]\ncom.canonical.AppMenu.Registrar=talk\n"), "{out}");
        assert!(out.contains("\nGTK_THEME=adw-gtk3-dark\n") && out.contains("\nXCURSOR_SIZE=24\n"), "{out}");
    }

    #[test]
    fn refuses_malformed_policy_and_dangling_keys() {
        let bad = |from: &str, to: &str| render(&SSOT.replace(from, to)).unwrap_err();
        assert!(bad("com.canonical.AppMenu.Registrar", "single").contains("well-known"));
        assert!(bad("com.canonical.AppMenu.Registrar", ":1.42").contains("well-known"));
        assert!(bad("com.canonical.AppMenu.Registrar", "a.b\\nc=own").contains("free of"));
        assert!(bad("\"appearance.gtk_theme\"", "\"appearance.nope\"").contains("not set"));
        assert!(bad("GTK_THEME =", "gtk-theme =").contains("environment variable"));
        assert!(render("[flatpak]\n").unwrap_err().contains("not declared"));
        assert!(bus_name("org.freedesktop.portal.*") && bus_name("org.kde.StatusNotifierWatcher") && !bus_name("org.1x"));
    }

    #[test]
    fn check_reports_drift_and_render_writes_atomically() {
        let t = tempfile::tempdir().unwrap();
        fs::create_dir_all(t.path().join("usr/share/mios")).unwrap();
        fs::write(t.path().join("usr/share/mios/mios.toml"), SSOT).unwrap();
        assert!(run(t.path(), true).unwrap_err().0.contains("DRIFT"), "missing file is drift");
        run(t.path(), false).unwrap();
        assert!(run(t.path(), true).unwrap().contains("matches"));
        fs::write(t.path().join(OUTPUT), "[Session Bus Policy]\nhand.edited=talk\n").unwrap();
        assert!(run(t.path(), true).unwrap_err().0.contains("DRIFT"), "a hand edit is drift");
    }
}
