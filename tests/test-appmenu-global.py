def judge(matrix, expect):
    """Assertions over the matrix. after: every fixture kind shows its menus with the right states, shortcuts and a
    real activation; before (main's exporter, no plugin): the NEWLY covered kinds yield no menu / no states."""
    rows = {r['case']: r for r in matrix}

    def row(n):
        return rows.get(n) or {}
    if expect == 'after':
        for n in ('fixture-qt6', 'fixture-gtk3', 'fixture-electron-like'):
            sh_ = row(n).get('shell')
            if sh_ is None:
                continue
            check(f'[{n}] shell: pills match the export, the dropdown shows the app\'s toggle states and shortcuts',
                  sh_.get('pills') == ['File', 'View'] and any(r[1] for r in sh_.get('rows', [])) and any(r[3] for r in sh_.get('rows', [])), sh_)
            check(f'[{n}] shell: REAL keys (virtual keyboard Down, Enter) activate the first View item and close the menu',
                  sh_.get('keys_activated') and sh_.get('closed_after_enter'), sh_)
        q = row('fixture-qt6')
        check('Qt 6 Wayland: menus bound to the exact window through the compositor (kde-appmenu), toggles + shortcuts',
              q.get('binding') == 'kde-appmenu' and q.get('menus') == ['File', 'View'] and q.get('toggles', 0) >= 3
              and q.get('shortcuts', 0) >= 2 and q.get('disabled', 0) >= 1 and (q.get('activate') or {}).get('observed')
              and (q.get('activate') or {}).get('state_after') is False, q)
        check('Qt 6: the process\'s second toplevel without a menubar gets no pills (exact per-window binding)',
              q.get('tool_window_menus') == [], q.get('tool_window_menus'))
        g3 = row('fixture-gtk3')
        check('GTK 3 GtkMenuBar on Wayland: accessible menu bar with submenu, check/radio state, accelerators, activation',
              g3.get('source') == 'accessibility' and g3.get('menus') == ['File', 'View'] and g3.get('toggles', 0) >= 3
              and g3.get('checked', 0) >= 2 and g3.get('shortcuts', 0) >= 2 and (g3.get('activate') or {}).get('observed'), g3)
        g4 = row('fixture-gtk4')
        check('GTK 4 GMenuModel menubar: stateful check/radio from org.gtk.Actions, accels, radio activation',
              g4.get('source') == 'gtk' and g4.get('menus') == ['File', 'View'] and g4.get('toggles', 0) >= 3
              and g4.get('shortcuts', 0) >= 1 and (g4.get('activate') or {}).get('observed'), g4)
        hb = row('fixture-gtk4-hamburger')
        check('GTK 4 menu-button-only app: its native menu button becomes a pill that presses it',
              hb.get('source') == 'accessibility' and hb.get('action_pills', 0) >= 1 and (hb.get('activate') or {}).get('observed'), hb)
        el = row('fixture-electron-like')
        check('Electron/Chromium-shaped KDE-appmenu exporter: bound by the compositor, toggles, shortcuts, submenu, activation',
              el.get('binding') == 'kde-appmenu' and el.get('menus') == ['File', 'View'] and el.get('toggles', 0) >= 5
              and el.get('shortcuts', 0) >= 3 and el.get('submenus', 0) >= 1 and (el.get('activate') or {}).get('observed'), el)
    elif expect == 'before':
        el = row('fixture-electron-like')
        check('NEGATIVE CONTROL (main): the Electron-shaped exporter offers no menu without the compositor protocol',
              el.get('mapped') and not el.get('menus'), el)
        for n in ('fixture-qt6', 'fixture-gtk3', 'fixture-gtk4'):
            r = row(n)
            check(f'NEGATIVE CONTROL (main): {n} has no toggle state or shortcut in the pills',
                  r.get('mapped') and r.get('toggles', 0) == 0 and r.get('shortcuts', 0) == 0, r)
        q = row('fixture-qt6')
        check('NEGATIVE CONTROL (main): the Qt fixture is paired by bus discovery, never by the compositor', q.get('binding') in (None, 'bus', 'registrar'), q)
        check('NEGATIVE CONTROL (main): the Qt tool window (no menubar) is handed the main window\'s menus',
              q.get('tool_window_menus') not in ([], None), q.get('tool_window_menus'))


