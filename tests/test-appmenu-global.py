def find_item(menus, path):
    """The item (or menu) at label path, matching labels by prefix after stripping ellipses/case."""
    norm = lambda s: re.sub(r'[….]+$', '', (s or '')).strip().lower()  # noqa: E731
    level = [{'label': m.get('label'), 'id': m.get('id'), 'action': m.get('action'), 'submenu': m.get('items')} for m in menus]
    node = None
    for want in path:
        node = next((n for n in level if norm(n.get('label')) == norm(want)), None) or \
            next((n for n in level if norm(n.get('label')).startswith(norm(want))), None)
        if node is None:
            return None
        level = node.get('submenu') or []
    return node


def summarize(menus):
    items = []

    def walk(xs):
        for x in xs or []:
            items.append(x)
            walk(x.get('submenu'))
    for m in menus:
        walk(m.get('items'))
    return {'menus': [m.get('label') for m in menus], 'items': len(items),
            'disabled': sum(1 for i in items if i.get('enabled') is False),
            'toggles': sum(1 for i in items if i.get('toggle')), 'checked': sum(1 for i in items if i.get('checked')),
            'shortcuts': sum(1 for i in items if i.get('shortcut')),
            'submenus': sum(1 for i in items if i.get('submenu')),
            'action_pills': sum(1 for m in menus if m.get('action'))}


