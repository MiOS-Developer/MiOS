def in_runtime(runtime):
    """PIDs whose environment names this nested runtime dir (our helpers and everything activated on our bus)."""
    out = []
    for p in Path('/proc').iterdir():
        if not p.name.isdigit() or int(p.name) == os.getpid():
            continue
        try:
            if f'XDG_RUNTIME_DIR={runtime}'.encode() in p.joinpath('environ').read_bytes().split(b'\0'):
                out.append(int(p.name))
        except OSError:
            pass
    return out


def primary_signature():
    """The parent (primary) compositor's instance: the inherited signature goes stale across compositor restarts, so
    take the instance whose lock names a live `Hyprland --watchdog-fd ...` (the login session), else the newest live one."""
    hypr = Path(UID_RUNTIME) / 'hypr'
    live = []
    for d in sorted(hypr.glob('*/'), key=lambda p: p.stat().st_mtime, reverse=True):
        try:
            pid = (d / 'hyprland.lock').read_text().split()[0]
            cmd = Path(f'/proc/{pid}/cmdline').read_bytes().replace(b'\0', b' ').decode()
        except (OSError, IndexError):
            continue
        if '--watchdog-fd' in cmd:
            return d.name
        live.append(d.name)
    return live[0] if live else None


