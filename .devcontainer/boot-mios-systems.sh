#!/usr/bin/env bash
# AI-hint: Single devcontainer lifecycle entrypoint: create, start, and platform setup retain the original ordered hooks and fail behavior.
set -euo pipefail

# The lifecycle commands run in the devcontainer's workspaceFolder, which is the
# [workspace] root holding every MiOS repo, not this repo; the relative paths
# below (.devloop_artifacts, harness/) are this repo's.
cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/.."

# The container runs as the account its own image's build created (the image's USER,
# from build.args.MIOS_IDENTITY_USERNAME), so attach never names a missing account.
# When the checkout's vendor [identity].username has changed since that build, only a
# rebuild provisions the new account: say so and stop before any lifecycle work.
mios_account_guard() {
    local root="$1" want have uid
    want="$(env -u MIOS_NATIVE_BIN_DIR MIOS_TOML_ROOT="$root" \
        python3 "${root}/usr/libexec/mios/mios-toml-get" --vendor identity username)" || want=""
    have="$(id -un)"; uid="$(id -u)"
    if [[ -z "$want" ]]; then
        echo "[devcontainer:account] ERROR: [identity].username did not resolve from ${root}" >&2
        exit 1
    fi
    if [[ "$have" != "$want" || "$uid" != 1000 ]]; then
        echo "[devcontainer:account] ERROR: this container runs as ${have} (UID ${uid}), but [identity].username is ${want} (UID 1000)." >&2
        echo "[devcontainer:account] The account is created when the image is built: rebuild the container (Codespaces: Rebuild Container, Full Rebuild)." >&2
        exit 1
    fi
}

mios_platform() {
    local platform config_dir
    if [[ -n "${CODESPACES:-}" ]]; then
        platform=codespaces
    elif [[ "${CLOUD_SHELL:-}" == "true" ]]; then
        platform=google-cloud-shell
    elif [[ -f /etc/oracle-release || -n "${OCI_CLI_CONFIG_FILE:-}" ]]; then
        platform=oracle-cloud-shell
    else
        platform=generic-devcontainer
    fi

    config_dir="${HOME}/.config/mios"
    install -d -m 0755 "${config_dir}"
    cat > "${config_dir}/devcontainer.env" <<EOF
# Generated by MiOS Dev Container post-create.
MIOS_DEVELOPMENT_PLATFORM=${platform}
MIOS_ARTIFACT_PROFILE=portable
EOF

    echo "[devcontainer:platform] ${platform}: portable MiOS development core configured."
    echo "[devcontainer:platform] Use .devcontainer/artifact-builder on a trusted host for privileged disk artifacts."
}

mios_core() {
    local root=/workspaces/MiOS
    local rust_manifest="${root}/src/mios-rs/Cargo.toml"
    local install_dir=/opt/mios/bin
    local agent_pipe_python=/usr/lib/mios/agents/.venv/bin/python
    local binary artifacts executables status

    if [[ ! -f "${rust_manifest}" ]]; then
        echo "[devcontainer:core] Missing miosd workspace manifest: ${rust_manifest}" >&2
        return 1
    fi
    if [[ ! -x "${agent_pipe_python}" ]]; then
        echo "[devcontainer:core] Missing agent-pipe runtime: ${agent_pipe_python}" >&2
        return 1
    fi

    echo "[devcontainer:core] Verifying agent-pipe runtime..."
    "${agent_pipe_python}" -c 'import fastapi, httpx, mcp, pydantic, uvicorn'

    echo "[devcontainer:core] Initializing MiOS developer state..."
    install -d -m 0755 \
        "${HOME}/.local/state/mios/agent-pipe" \
        "${HOME}/.local/state/mios/daemon" \
        "${HOME}/.local/share/mios/agent-pipe" \
        "${HOME}/.cache/mios/agent-pipe"

    echo "[devcontainer:core] Building upstream native workspaces..."
    artifacts="$(mktemp)"
    if (cd "${root}/src/mios-rs" && cargo build --locked --release --message-format=json-render-diagnostics) >"${artifacts}" \
        && (cd "${root}/tools/native" && cargo build --locked --release --workspace --exclude mios-wallpaperd --message-format=json-render-diagnostics) >>"${artifacts}"; then
        :
    else
        status=$?
        rm -f "${artifacts}"
        return "$status"
    fi
    # Cargo reports actual executable paths, including configured target triples
    # and custom CARGO_TARGET_DIR locations. A target/release glob silently kept
    # the baked tools when tools/native built its configured musl target instead.
    if executables="$(python3 - "${artifacts}" <<'PY'
import json, sys
executables = {}
for line in open(sys.argv[1], encoding="utf-8"):
    artifact = json.loads(line)
    target = artifact.get("target", {})
    name = target.get("name", "")
    executable = artifact.get("executable")
    if (artifact.get("reason") == "compiler-artifact" and "bin" in target.get("kind", [])
            and (name.startswith("mios") or name == "generate-names-registry") and executable):
        executables[name] = executable
if not {"miosd", "mios-gen"}.issubset(executables):
    raise SystemExit("[devcontainer:core] Cargo did not report the required miosd and mios-gen executables")
print("\n".join(executables.values()))
PY
    )"; then
        rm -f "${artifacts}"
    else
        status=$?
        rm -f "${artifacts}"
        return "$status"
    fi
    sudo install -d -m 0755 "${install_dir}"
    while IFS= read -r binary; do
        [[ -n "${binary}" ]] || continue
        sudo install -m 0755 "${binary}" "${install_dir}/$(basename "${binary}")"
    done <<<"${executables}"
    sudo ln -sfn "${install_dir}/miosd" /usr/local/bin/miosd
    # The rest of this lifecycle must use this source's tools and generator
    # helpers rather than finding the image's older catalog first.
    export PATH="${install_dir}:${PATH}"
    export MIOS_NATIVE_BIN_DIR="${install_dir}"
    miosd --help >/dev/null

    echo "[devcontainer:core] MiOS development core is ready."
}

mios_create() {
    echo "[devcontainer:post-create] Initializing embedded agent harness..."
    mkdir -p .devloop_artifacts .worktrees
    git config --global --add safe.directory /workspaces/MiOS
    bash /workspaces/MiOS/.devcontainer/setup-devcontainer.sh
    mios_core
    echo "[devcontainer:post-create] Full MiOS workspace and harness are ready."
}

# The node's launch parameters are SSOT [tailscale] (a cloud deployment takes
# [deployment.cloud.overlay.tailscale]: userspace mode, loopback SOCKS5, exit node,
# shields up); mios-tailscale-sync enrolls it from a pre-auth key file.
start_tailscale_mesh() {
    command -v tailscaled >/dev/null 2>&1 || return 0
    local ts_state="${XDG_STATE_HOME:-${HOME}/.local/state}/mios/tailscale"
    local toml_get=/usr/libexec/mios/mios-toml-get mode socks5
    [[ -f /workspaces/MiOS/usr/libexec/mios/mios-toml-get ]] && toml_get=/workspaces/MiOS/usr/libexec/mios/mios-toml-get
    mode="$("$toml_get" tailscale mode kernel 2>/dev/null || echo kernel)"
    socks5="$("$toml_get" tailscale socks5_server "" 2>/dev/null || true)"
    (umask 077 && mkdir -p "$ts_state") && chmod 0700 "$ts_state"
    if ! pgrep -x tailscaled >/dev/null 2>&1; then
        local args=(--statedir="$ts_state" --socket="$ts_state/tailscaled.sock")
        [[ "$mode" == userspace || ! -e /dev/net/tun ]] && args+=(--tun=userspace-networking)
        [[ -n "$socks5" ]] && args+=(--socks5-server="$socks5")
        (umask 077 && setsid tailscaled "${args[@]}" >"$ts_state/tailscaled.log" 2>&1 </dev/null &)
        for _ in $(seq 1 20); do [[ -S "$ts_state/tailscaled.sock" ]] && break; sleep 0.5; done
    fi
    if [[ -x /usr/libexec/mios/mios-tailscale-sync ]]; then
        MIOS_TAILSCALE_AUTHKEY="${MIOS_TAILSCALE_AUTHKEY:-${TS_AUTHKEY:-${TAILSCALE_AUTHKEY:-}}}" \
            /usr/libexec/mios/mios-tailscale-sync --socket="$ts_state/tailscaled.sock" \
            >>"$ts_state/sync.log" 2>&1 || true
    fi
}

start_mios_mcp_gateway() {
    local root="${1:-/workspaces/MiOS}"
    local mcp_py="/usr/lib/mios/mcp/.venv/bin/python3"
    [[ -x "$mcp_py" ]] || return 0
    local toml_get="${root}/usr/libexec/mios/mios-toml-get"
    [[ -f "$toml_get" ]] || toml_get=/usr/libexec/mios/mios-toml-get
    local mcp_port
    mcp_port="$("$mcp_py" "$toml_get" ports mcp 2>/dev/null || echo 8770)"
    local pipe_port
    pipe_port="$("$mcp_py" "$toml_get" ports agent_pipe 2>/dev/null || echo 8700)"
    if ! (exec 3<>"/dev/tcp/127.0.0.1/${mcp_port}") 2>/dev/null; then
        local mcp_log="${XDG_STATE_HOME:-${HOME}/.local/state}/mios/mios-mcp-http.log"
        mkdir -p "$(dirname "$mcp_log")"
        MIOS_MCP_TAILNET_DISCOVER=1 MIOS_A2A_TAILNET_DISCOVER=1 \
            setsid "$mcp_py" /usr/libexec/mios/mios-mcp-server --http --host 127.0.0.1 --port "$mcp_port" \
            >"$mcp_log" 2>&1 </dev/null &
    fi
    local ts_sock="${XDG_STATE_HOME:-${HOME}/.local/state}/mios/tailscale/tailscaled.sock"
    local ts_args=()
    [[ -S "$ts_sock" ]] && ts_args=(--socket="$ts_sock")
    if command -v tailscale >/dev/null 2>&1 && tailscale "${ts_args[@]}" status >/dev/null 2>&1; then
        tailscale "${ts_args[@]}" serve --bg "$pipe_port" >/dev/null 2>&1 || true
        tailscale "${ts_args[@]}" serve --bg "$mcp_port" >/dev/null 2>&1 || true
    fi
    if [[ -x /usr/libexec/mios/mios-a2a-discover ]]; then
        MIOS_A2A_TAILNET_DISCOVER=1 "$mcp_py" /usr/libexec/mios/mios-a2a-discover >/dev/null 2>&1 || true
    fi
}

connect_remote_agy_blade() {
    local mcp_py="/usr/lib/mios/mcp/.venv/bin/python3"
    local state_dir="${XDG_STATE_HOME:-${HOME}/.local/state}/mios"
    mkdir -p "$state_dir"
    local blade_host="${MIOS_BLADE_HOST:-}"
    if [[ -z "$blade_host" ]] && command -v tailscale >/dev/null 2>&1 && [[ -x "$mcp_py" ]]; then
        blade_host="$(MIOS_MCP_TAILNET_DISCOVER=1 "$mcp_py" -c '
import sys
sys.path.insert(0, "/workspaces/MiOS/usr/lib/mios")
import mios_mcp_federation as fed
peers = fed.discover_tailnet_upstreams()
print(peers[0]["ip"] if peers else "")
' 2>/dev/null || true)"
    fi
    if [[ -n "$blade_host" ]]; then
        local blade_mcp="${MIOS_BLADE_MCP_URL:-http://${blade_host}:8770/mcp}"
        local blade_ai="http://${blade_host}:8700/v1"
        {
            printf 'export MIOS_BLADE_HOST=%q\n' "$blade_host"
            printf 'export MIOS_BLADE_MCP_URL=%q\n' "$blade_mcp"
            printf 'export MIOS_BLADE_AI_ENDPOINT=%q\n' "$blade_ai"
        } > "$state_dir/blade-session.env"
    fi
    if [[ -x /usr/libexec/mios/mios-agent-relay ]]; then
        /usr/libexec/mios/mios-agent-relay register --agent-id "codespace-$(hostname -s 2>/dev/null || echo dev)" --kind agy >/dev/null 2>&1 || true
    fi
    local agy_host="/workspaces/-dev-loop/skills/dev-loop/scripts/agy_host.sh"
    if [[ "${MIOS_BLADE_REMOTE_CONTROL:-${AGY_REMOTE_CONTROL:-0}}" == "1" && -f "$agy_host" ]] && command -v agy >/dev/null 2>&1; then
        pgrep -f "agy.*--remote-control" >/dev/null 2>&1 || \
            setsid bash "$agy_host" --session --remote-control >"$state_dir/agy-remote-control.log" 2>&1 </dev/null &
    fi
}

mios_start() {
    readonly ROOT=/workspaces/MiOS

    if ! git -C "$ROOT" rev-parse --git-dir >/dev/null 2>&1; then
        echo "[devcontainer:boot] MiOS workspace is unavailable: ${ROOT}" >&2
        exit 1
    fi
    if ! command -v sudo >/dev/null 2>&1; then
        echo "[devcontainer:boot] sudo is required to apply the MiOS root overlay" >&2
        exit 1
    fi

    echo "[devcontainer:boot] Applying MiOS system overlay..."
    sudo bash "${ROOT}/.devcontainer/install-root-overlay.sh"
    # The same image as every MiOS; as a cloud/container deployment it takes the
    # [deployment.cloud] host drop-in: no runtime model pulls, desktop installs or session.
    sudo bash "${ROOT}/.devcontainer/cloud-shell/bootstrap.sh" overlay --apply

    echo "[devcontainer:boot] Reconciling MiOS development core..."
    mios_core
    mios_platform
    start_tailscale_mesh
    bash "${ROOT}/.devcontainer/mios-agent-pipe-dev" start
    start_mios_mcp_gateway "$ROOT"
    connect_remote_agy_blade
    /usr/lib/mios/mcp/.venv/bin/python3 /usr/libexec/mios/mios-mcp-server --project-agent-clients

    # Re-seed the live editor Machine/settings.json from .dotfiles on every start:
    # these paths are regenerated by the client on reconnect/version-bump and drop
    # the theme/frameless projection applied by postCreateCommand exactly once.
    echo "[devcontainer:boot] Re-projecting .dotfiles SSOT into the live editor profile..."
    python3 "${ROOT}/tools/sync-dotfiles.py" || echo "[devcontainer:boot] sync-dotfiles.py failed; continuing" >&2

    for required in podman bootc miosd; do
        if ! command -v "${required}" >/dev/null 2>&1; then
            echo "[devcontainer:boot] Missing required MiOS component: ${required}" >&2
            exit 1
        fi
    done

    echo "[devcontainer:boot] MiOS systems are installed and ready."
}

mios_post_start() {
    echo "[devcontainer:post-start] Checking agentic environment and AI endpoint..."

    # postCreateCommand only ever runs once per container lifetime, so a
    # transient network failure there (e.g. agy's release-manifest endpoint
    # unreachable at creation time) would otherwise never be retried. Re-check
    # and self-heal on every start instead; best-effort, never fails the gate.
    if ! command -v agy >/dev/null 2>&1; then
        echo "[devcontainer:post-start] agy missing; retrying install..."
        tmp="$(mktemp -d)"
        if bash /workspaces/MiOS/.devcontainer/fetch-installer.sh \
             https://antigravity.google/cli/install.sh "${tmp}/install.sh" \
           && bash "${tmp}/install.sh" >/dev/null 2>&1; then
            echo "[devcontainer:post-start] agy installed: $(agy --version 2>/dev/null || echo unknown)"
        else
            echo "[devcontainer:post-start] agy still unreachable; will retry next start"
        fi
        rm -rf "${tmp}"
    fi

    # The credential keyring is a process, so it is gone after every restart and
    # agy re-asks for authentication without it. Best-effort, like the install above.
    DEVLOOP_ENV=/workspaces/-dev-loop/skills/dev-loop/scripts/env
    if [ -r "${DEVLOOP_ENV}/agy-keyring.sh" ]; then
        # shellcheck source=/dev/null
        . "${DEVLOOP_ENV}/agy-keyring.sh" || echo "[devcontainer:post-start] keyring not started; agy will ask to authenticate"
    fi

    # code-server once per start, loopback only, on [ports].code_server; its generated password stays in ~/.config/code-server.
    MIOS_TOML_GET=/workspaces/MiOS/usr/libexec/mios/mios-toml-get
    [ -f "$MIOS_TOML_GET" ] || MIOS_TOML_GET=/usr/libexec/mios/mios-toml-get
    cs_port="$(python3 "$MIOS_TOML_GET" ports code_server)"
    case "$cs_port" in
        ''|*[!0-9]*) echo "[devcontainer:post-start] ERROR: [ports].code_server did not resolve (got '${cs_port}')" >&2; exit 1 ;;
    esac
    if (exec 3<>"/dev/tcp/127.0.0.1/${cs_port}") 2>/dev/null; then
        echo "[devcontainer:post-start] code-server already listening on 127.0.0.1:${cs_port}"
    elif command -v code-server >/dev/null 2>&1; then
        cs_log="${XDG_STATE_HOME:-${HOME}/.local/state}/mios/code-server.log"
        mkdir -p "$(dirname "$cs_log")"
        setsid code-server --bind-addr "127.0.0.1:${cs_port}" >"$cs_log" 2>&1 </dev/null &
        echo "[devcontainer:post-start] code-server started on 127.0.0.1:${cs_port} (pid $!, log ${cs_log})"
    else
        echo "[devcontainer:post-start] ERROR: code-server is missing; the MiOS image bakes it (automation/59-tools.sh), so rebuild or re-pull the image" >&2
        exit 1
    fi

    # Use the gateway's shipped readiness probe. The former harness/ gate was
    # never part of this checkout and failed every otherwise successful start.
    bash /workspaces/MiOS/.devcontainer/mios-agent-pipe-dev check

    echo "[devcontainer:post-start] Ready for agent dispatch."
}

case "${1:-start}" in
    create)
        mios_account_guard "$PWD"
        mios_create
        mios_platform
        ;;
    start)
        mios_account_guard "$PWD"
        mios_start
        mios_post_start
        ;;
    platform)
        mios_platform
        ;;
    --help|-h)
        printf 'Usage: %s [create|start|platform]\n' "$0"
        ;;
    *)
        printf 'Unknown devcontainer lifecycle mode: %s\n' "$1" >&2
        exit 2
        ;;
esac
